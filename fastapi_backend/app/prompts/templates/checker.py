BOOK_GROUNDING_RULES = """
判斷原則（很重要）：
- 先把學生文字理解成一個或多個「誰－做了什麼－對什麼／造成什麼結果」的故事主張，再逐項和 BOOK_CONTEXT 核對；不可只查單字。
- 語意相同的改寫、角色簡稱、合理省略非關鍵細節都算 supported，不要求教材原句。
- O 段最嚴格：每個具體故事主張都要能由教材支持。只要其中一個重要主張 contradicted 或 ambiguous，整體就不得填 supported。
- contradicted：人物、動作、物品、對象、順序或因果與教材明確不同，或新增教材完全沒有的事件。
- ambiguous：句子省略了核對所需的關鍵資訊，例如「他後來就收起來」沒有說收了什麼；禁止自行腦補成教材中的正確事件。
- 「一些東西／那些東西／把東西收起來」等泛稱，只有前文已清楚指出是哪個教材物品時才可視為有指涉；若全文都沒有交代具體是什麼，必須判 ambiguous。
- 「無聊的東西／有趣的東西」是學生評價，不能代替 O 段應寫清楚的具體教材事件或物品。
- R/I 段（重要，比 O 段寬鬆）：
  - 感受本身（覺得、生氣、開心）可以完全來自學生，不需要書裡的原句。
  - 用來支持感受／體會的故事主張仍須由教材支持；只有個人感受或觀點不必出現在教材。
  - unsupported_span 禁止把整句個人感受一刀切，只摘出不受教材支持或資訊不清的故事片段。
- D 段寫學生自己的生活行動，不要求出現教材人物、物品或事件；只在學生明確捏造故事情節時才判 contradicted。
- ALL 代表偶數週整合短文：只核對文中的具體故事主張。學生自己的感受、想法、生活經驗、體會與未來行動不需要出現在教材，也不可因此判 ambiguous 或 contradicted。
- ALL 中若一個句子同時包含故事與個人反思，只把不受教材支持或指涉不清的故事片段列入 claims；不要把整句個人反思判錯。
- unsupported_span 必須是學生原文中的連續文字，優先摘「動詞＋受詞」或資訊不清的短句，不要抄整段。
- 不確定時使用 ambiguous，不可猜測學生原意，也不可把 ambiguous 當成 supported。
""".strip()
